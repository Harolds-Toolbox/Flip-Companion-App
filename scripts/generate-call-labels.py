#!/usr/bin/env python3
"""Generate localized Android CallStyle labels from AOSP framework resources.

Source: https://android.googlesource.com/platform/frameworks/base/+/refs/heads/main/core/res/res/
The extracted strings are from Android Open Source Project (Apache License 2.0).
These labels supplement, rather than replace, service-specific call controls.
"""

import concurrent.futures
import json
import re
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = "https://android.googlesource.com/platform/frameworks/base/+/refs/heads/main/core/res/res"
RAW = "https://raw.githubusercontent.com/aosp-mirror/platform_frameworks_base/master/core/res/res"
NAMES = {
    "answers": "call_notification_answer_action",
    "video_answers": "call_notification_answer_video_action",
    "declines": "call_notification_decline_action",
    "hangups": "call_notification_hang_up_action",
    "incoming": "call_notification_incoming_text",
    "ongoing": "call_notification_ongoing_text",
}


def fetch(directory):
    url = f"{RAW}/{directory}/strings.xml"
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            xml = response.read()
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return directory, {}
        raise
    values = {}
    for node in ET.fromstring(xml):
        name = node.get("name")
        if name in NAMES.values():
            value = "".join(node.itertext()).strip().strip('"').strip()
            if value:
                values[name] = value
    return directory, values


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def main():
    with urllib.request.urlopen(f"{ROOT}/?format=JSON", timeout=30) as response:
        directory = json.loads(response.read().decode()[4:])
    locale_pattern = re.compile(r"values-(?:[a-z]{2,3}(?:-r[A-Z]{2})?|b\+[a-z]{2,3}\+[A-Za-z]{4}(?:\+[A-Z]{2})?)$")
    folders = ["values"] + sorted(
        item["name"] for item in directory["entries"] if locale_pattern.fullmatch(item["name"])
    )
    labels = {role: set() for role in NAMES}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for folder, values in pool.map(fetch, folders):
            if folder == "values" and len(values) != len(NAMES):
                raise RuntimeError("Default Android call labels are incomplete")
            for role, name in NAMES.items():
                if name in values:
                    labels[role].add(values[name])
    if "Απάντηση" not in labels["answers"] or "Τερματισμός" not in labels["hangups"]:
        raise RuntimeError("Greek call labels were not extracted")
    lines = [
        "package uk.co.flipwhatsapphangup",
        "",
        "// Generated by scripts/generate-call-labels.py from AOSP framework CallStyle strings.",
        "// AOSP resource strings are licensed under Apache License 2.0.",
        "internal object AndroidCallLabels {",
    ]
    for role, values in labels.items():
        lines.append(f"    val {role} = setOf(")
        lines.extend(f"        {literal(value)}," for value in sorted(values))
        lines.append("    )")
    lines.append("}")
    output = Path(__file__).resolve().parents[1] / "app/src/main/java/uk/co/flipwhatsapphangup/AndroidCallLabels.kt"
    output.write_text("\n".join(lines) + "\n")
    print(f"Generated {output} from {len(folders)} Android locale directories")
    print("Distinct labels: " + ", ".join(f"{role}={len(values)}" for role, values in labels.items()))


if __name__ == "__main__":
    main()
